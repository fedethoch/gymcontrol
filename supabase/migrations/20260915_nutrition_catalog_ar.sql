-- 2) Alimento de prueba "test": si lo registro una sola cuenta pasa a ser privado de esa cuenta
--    (su historial queda intacto); si nadie lo usa, se borra.
update public.foods f
set owner_user_id = usage.user_id
from (
  select i.food_id, min(ml.user_id::text)::uuid as user_id
  from public.meal_log_items i
  join public.meal_logs ml on ml.id = i.meal_log_id
  group by i.food_id
  having count(distinct ml.user_id) = 1
) usage
where f.name = 'test' and f.owner_user_id is null and usage.food_id = f.id;

delete from public.foods f
where f.name = 'test'
  and f.owner_user_id is null
  and not exists (select 1 from public.meal_log_items i where i.food_id = f.id)
  and not exists (select 1 from public.recipe_items ri where ri.food_id = f.id);

